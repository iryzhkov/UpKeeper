// Package author implements `upkeeper author`: edit the release manifest in a
// checkout to pin a Steward release and an omarchy-setup commit, and refresh
// the agent-environment files that derive from that commit.
//
// It is the authored counterpart of a capture. A capture photographs one host;
// an authored release is computed from its inputs alone, so the same Steward
// version, omarchy-setup commit and UpKeeper HEAD always produce the same
// bytes, whatever the host running it has installed. Nothing on the host is
// read except the omarchy-setup clone the commit is taken from, and nothing is
// committed, pushed or converged: the result is reviewed as a Git diff and
// published with `upkeeper push --authored`.
package author

import (
	"archive/tar"
	"bytes"
	"errors"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"

	"github.com/iryzhkov/UpKeeper/internal/agentenv"
	"github.com/iryzhkov/UpKeeper/internal/canonjson"
	"github.com/iryzhkov/UpKeeper/internal/failure"
	"github.com/iryzhkov/UpKeeper/internal/inventory"
	"github.com/iryzhkov/UpKeeper/internal/procx"
	"github.com/iryzhkov/UpKeeper/internal/release"
	"github.com/iryzhkov/UpKeeper/internal/safety"
)

// Generator is where an omarchy-setup checkout keeps the program that writes
// the shared agent instructions. The copy in the pinned commit is run, never
// one installed on this host, so the generated bytes depend on the commit only.
const Generator = "config/bin/agents-instructions-gen"

// skillsDirectory is where an omarchy-setup checkout keeps the skills it owns.
const skillsDirectory = "config/claude/skills"

// instructionDirectory is the home-relative directory the generator owns.
const instructionDirectory = ".config/agents"

// temporaryRelease is where the new manifest is written before it is renamed
// over desired/release.json.
const temporaryRelease = "desired/.release.json.tmp"

// abbreviatedCommit is the spelling --omarchy-setup accepts: hexadecimal, so
// that a branch name, which moves, can never be mistaken for a pin.
var abbreviatedCommit = regexp.MustCompile(`^[0-9a-f]{7,40}$`)

// Options are the inputs of one authored release.
type Options struct {
	// Steward is the t3-steward release version to pin.
	Steward string
	// SetupCommit is the omarchy-setup commit to pin, full or abbreviated.
	SetupCommit string
	// SetupRepository is a local omarchy-setup clone that has, or can fetch,
	// the commit.
	SetupRepository string
	// DryRun computes and validates the release without writing it.
	DryRun bool
	Runner procx.Runner
}

// Pin is one version field the authored release set.
type Pin struct {
	Name string
	From string
	To   string
}

// Result is what an authored release changed.
type Result struct {
	Head                  string
	SetupCommit           string
	Pins                  []Pin
	Files                 []agentenv.Refresh
	PreviousReleaseSHA256 string
	ReleaseSHA256         string
	// Changed is whether the release bytes differ from the checkout's.
	Changed bool
	// Written is whether desired/release.json was replaced.
	Written bool
	Notes   []string
}

// Run authors the release in the checkout at root.
func Run(root string, options Options) (Result, error) {
	runner := options.Runner
	if runner == nil {
		runner = procx.Run
	}
	if _, err := release.ValidateVersion(options.Steward, "t3-steward"); err != nil {
		return Result{}, err
	}
	if !abbreviatedCommit.MatchString(options.SetupCommit) {
		return Result{}, failure.Validation(
			"--omarchy-setup must be a lowercase hexadecimal commit, not %q", options.SetupCommit)
	}
	if options.SetupRepository == "" {
		return Result{}, failure.Validation("no omarchy-setup repository was named")
	}
	if err := refuseUnrelatedChanges(runner, root); err != nil {
		return Result{}, err
	}
	head, err := git(runner, root, 30*time.Second, "rev-parse", "--verify", "HEAD^{commit}")
	if err != nil {
		return Result{}, err
	}

	path := filepath.Join(root, release.File)
	original, err := os.ReadFile(path)
	if err != nil {
		return Result{}, failure.Validation("cannot read %s: %v", release.File, err)
	}
	manifest, err := canonjson.DecodeObject(original)
	if err != nil {
		return Result{}, failure.Validation("cannot load %s: %v", release.File, err)
	}
	// Every byte outside the fields this command owns has to survive, and the
	// only way to be sure of that is a file that is already in the encoding it
	// will be written back in.
	if canonical, err := canonjson.MarshalFile(manifest); err != nil || !bytes.Equal(canonical, original) {
		return Result{}, failure.Validation(
			"%s is not in its canonical encoding, so an edit could not preserve its other bytes", release.File)
	}
	validated, err := release.Validate(manifest)
	if err != nil {
		return Result{}, err
	}
	var policy []byte
	if document, present, err := validated.FleetIntent(); err != nil {
		return Result{}, err
	} else if present {
		// Use the exact immutable rendering fleet convergence will install.
		policy = document.RoutePolicyBytes()
	}
	components, _ := manifest["components"].(map[string]any)
	setup, _ := components["omarchy-setup"].(map[string]any)
	steward, _ := components["t3-steward"].(map[string]any)
	t3, _ := components["t3"].(map[string]any)
	compatibility, _ := t3["compatibility"].(map[string]any)
	environment, _ := components["agent-environment"].(map[string]any)
	if setup == nil || steward == nil || compatibility == nil || environment == nil {
		return Result{}, failure.Validation(
			"an authored release needs the omarchy-setup, t3-steward, t3 and agent-environment components")
	}

	repository, err := filepath.Abs(options.SetupRepository)
	if err != nil {
		return Result{}, failure.Validation("cannot resolve the omarchy-setup repository: %v", err)
	}
	ref, _ := setup["ref"].(string)
	source, _ := setup["source"].(string)
	if err := checkOrigin(runner, repository, source); err != nil {
		return Result{}, err
	}
	commit, err := resolveSetupCommit(runner, repository, options.SetupCommit, ref)
	if err != nil {
		return Result{}, err
	}
	result := Result{Head: head, SetupCommit: commit, PreviousReleaseSHA256: digestOf(original)}
	previousCommit, _ := setup["commit"].(string)
	former, err := formerSkills(runner, repository, previousCommit)
	if err != nil {
		return Result{}, err
	}

	scratch, err := os.MkdirTemp("", "upkeeper-author-*")
	if err != nil {
		return Result{}, err
	}
	defer os.RemoveAll(scratch)
	checkout := filepath.Join(scratch, "checkout")
	if err := extract(runner, repository, commit, checkout); err != nil {
		return Result{}, err
	}
	sources, err := derive(runner, scratch, checkout, policy)
	if err != nil {
		return Result{}, err
	}
	sources.FormerSkills = former

	for _, pin := range []struct {
		name   string
		object map[string]any
		key    string
		value  string
	}{
		{"t3-steward.version", steward, "version", options.Steward},
		{"t3.compatibility.steward_version", compatibility, "steward_version", options.Steward},
		{"omarchy-setup.commit", setup, "commit", commit},
	} {
		before, _ := pin.object[pin.key].(string)
		if before != pin.value {
			result.Pins = append(result.Pins, Pin{Name: pin.name, From: before, To: pin.value})
		}
		pin.object[pin.key] = pin.value
	}
	refreshed, files, err := agentenv.RefreshDerived(environment, sources, head)
	if err != nil {
		return Result{}, failure.Validation("agent-environment: %s", err.Error())
	}
	components["agent-environment"] = refreshed
	result.Files = files

	value, err := validate(root, manifest)
	if err != nil {
		return Result{}, err
	}
	payload, err := value.CanonicalBytes()
	if err != nil {
		return Result{}, err
	}
	result.ReleaseSHA256 = digestOf(payload)
	result.Changed = !bytes.Equal(payload, original)
	if options.DryRun || !result.Changed {
		return result, nil
	}
	temporary := filepath.Join(root, temporaryRelease)
	if err := os.WriteFile(temporary, payload, 0o644); err != nil {
		return Result{}, err
	}
	if err := os.Rename(temporary, path); err != nil {
		_ = os.Remove(temporary)
		return Result{}, err
	}
	result.Written = true
	return result, nil
}

// refuseUnrelatedChanges allows the checkout one kind of local change: an
// edit to desired/release.json itself, so that an authored release can be
// recomputed after a mistake without a commit in between. Anything else,
// tracked or untracked, is refused, because the release is reviewed as the
// diff of one file and published from a HEAD it names.
func refuseUnrelatedChanges(runner procx.Runner, root string) error {
	// The output is read untrimmed: its first column is significant, and a
	// leading space is how Git says a file is changed but not staged.
	status := runner(procx.Command{
		Argv:    []string{"git", "-C", root, "status", "--porcelain=v1", "--untracked-files=all"},
		Timeout: 30 * time.Second,
	})
	if !status.OK() {
		return failure.Validation("git status failed in %s: %s", root, tail(strings.TrimSpace(status.Output()), 300))
	}
	unrelated := []string{}
	for _, line := range strings.Split(status.Stdout, "\n") {
		if len(line) < 4 {
			continue
		}
		code, path := line[:2], line[3:]
		if path == release.File && strings.Trim(code, "M ") == "" {
			continue
		}
		// A run interrupted between writing and renaming leaves this behind;
		// the next write replaces it.
		if path == temporaryRelease && code == "??" {
			continue
		}
		unrelated = append(unrelated, path)
	}
	if len(unrelated) > 0 {
		return failure.Validation(
			"the checkout has changes other than %s; commit or remove them first: %s",
			release.File, strings.Join(unrelated, ", "))
	}
	return nil
}

// checkOrigin refuses a clone whose origin is not the repository the release
// names as omarchy-setup's source. The pinned commit's generator is run on this
// machine, so a fork or a stale mirror as origin would mean running code the
// release never named. The configured URL is compared, not the one insteadOf
// rewriting produces: what the operator's own Git configuration redirects to
// is theirs to decide.
func checkOrigin(runner procx.Runner, repository, source string) error {
	configured, err := git(runner, repository, 30*time.Second, "config", "--get", "remote.origin.url")
	if err != nil {
		return failure.Validation("omarchy-setup: %s has no origin remote", repository)
	}
	if sameRepository(configured, source) {
		return nil
	}
	return failure.Validation(
		"omarchy-setup: origin of %s is %s, but the release takes omarchy-setup from %s",
		repository, configured, source)
}

// sameRepository compares two Git URLs by host and path, so that the https,
// ssh:// and scp-like spellings of one repository, with or without .git or a
// trailing slash, are the same repository.
func sameRepository(left, right string) bool {
	normal := func(value string) string {
		value = strings.TrimSpace(value)
		if scheme := strings.Index(value, "://"); scheme >= 0 {
			value = value[scheme+3:]
		} else if colon := strings.Index(value, ":"); colon >= 0 && !strings.Contains(value[:colon], "/") {
			value = value[:colon] + "/" + value[colon+1:]
		}
		if at := strings.Index(value, "@"); at >= 0 && at < strings.Index(value+"/", "/") {
			value = value[at+1:]
		}
		value = strings.TrimSuffix(strings.TrimSuffix(value, "/"), ".git")
		host, path, _ := strings.Cut(value, "/")
		if colon := strings.Index(host, ":"); colon >= 0 {
			host = host[:colon]
		}
		return strings.ToLower(host) + "/" + path
	}
	return left != "" && right != "" && normal(left) == normal(right)
}

// resolveSetupCommit fetches the ref the release follows and resolves the
// commit to its full name, refusing one that ref does not reach: a target can
// only fetch what origin/<ref> reaches, which is the rule capture applies to
// the commit it publishes.
func resolveSetupCommit(runner procx.Runner, repository, commit, ref string) (string, error) {
	if _, err := release.ValidateRef(ref, "omarchy-setup"); err != nil {
		return "", err
	}
	fetched := runner(procx.Command{
		Argv:    []string{"git", "-C", repository, "fetch", "--quiet", "origin", ref},
		Env:     procx.GitEnvironment(),
		Timeout: 90 * time.Second,
	})
	if !fetched.OK() {
		return "", failure.Validation("omarchy-setup: cannot fetch origin/%s in %s: %s",
			ref, repository, tail(strings.TrimSpace(fetched.Output()), 300))
	}
	resolved, err := git(runner, repository, 30*time.Second,
		"rev-parse", "--verify", "--quiet", "--end-of-options", commit+"^{commit}")
	if err != nil {
		return "", failure.Validation("omarchy-setup: %s is not a commit in %s", commit, repository)
	}
	if _, err := safety.ValidateGitCommit(resolved); err != nil {
		return "", err
	}
	reachable := runner(procx.Command{
		Argv:    []string{"git", "-C", repository, "merge-base", "--is-ancestor", resolved, "FETCH_HEAD"},
		Timeout: 30 * time.Second,
	})
	if !reachable.OK() {
		return "", failure.Validation(
			"omarchy-setup: commit %s is not on origin/%s; push it there before authoring a release",
			resolved[:12], ref)
	}
	return resolved, nil
}

// formerSkills lists the skills the currently pinned commit owns, so that a
// skill the new commit deleted is retired instead of being left in the release
// as if it were somebody's personal skill. Retirement goes by skill name, so
// without this list a dropped skill would be published forever; a previous pin
// that cannot be read is therefore a refusal, not a warning.
func formerSkills(runner procx.Runner, repository, commit string) ([]string, error) {
	if _, err := safety.ValidateGitCommit(commit); err != nil {
		return nil, failure.Validation("the release pins no full omarchy-setup commit to retire skills against")
	}
	if _, err := git(runner, repository, 30*time.Second,
		"rev-parse", "--verify", "--quiet", "--end-of-options", commit+"^{commit}"); err != nil {
		return nil, failure.Validation(
			"omarchy-setup: the previously pinned commit %s is not in %s; fetch it first, "+
				"because without it a skill the new commit removed cannot be retired", commit[:12], repository)
	}
	listing, err := git(runner, repository, 30*time.Second,
		"ls-tree", "-d", "--name-only", commit, "--", skillsDirectory+"/")
	if err != nil {
		return nil, err
	}
	names := []string{}
	for _, name := range strings.Split(listing, "\n") {
		if name != "" {
			names = append(names, strings.TrimPrefix(name, skillsDirectory+"/"))
		}
	}
	sort.Strings(names)
	return names, nil
}

// extract writes the tree of one commit to a fresh directory. It reads the
// object database only: the repository's working tree, index and worktree
// list are never touched, so nothing has to be cleaned up there afterwards.
func extract(runner procx.Runner, repository, commit, destination string) error {
	archived := runner(procx.Command{
		Argv:    []string{"git", "-C", repository, "archive", "--format=tar", commit},
		Timeout: 120 * time.Second,
	})
	if !archived.OK() {
		return failure.Validation("omarchy-setup: cannot read commit %s: %s",
			commit[:12], tail(strings.TrimSpace(archived.Stderr), 300))
	}
	if err := os.MkdirAll(destination, 0o700); err != nil {
		return err
	}
	reader := tar.NewReader(strings.NewReader(archived.Stdout))
	for {
		header, err := reader.Next()
		if errors.Is(err, io.EOF) {
			return nil
		}
		if err != nil {
			return failure.Validation("omarchy-setup: cannot read commit %s: %v", commit[:12], err)
		}
		name := filepath.Clean(filepath.FromSlash(header.Name))
		if filepath.IsAbs(name) || name == ".." || strings.HasPrefix(name, ".."+string(filepath.Separator)) {
			return failure.Validation("omarchy-setup: commit %s names an unsafe path", commit[:12])
		}
		target := filepath.Join(destination, name)
		switch header.Typeflag {
		case tar.TypeDir:
			err = os.MkdirAll(target, 0o755)
		case tar.TypeReg:
			if err = os.MkdirAll(filepath.Dir(target), 0o755); err == nil {
				err = writeExtracted(target, reader, gitMode(header.Mode))
			}
		case tar.TypeSymlink:
			// A link may point within the tree and nowhere else: the generator
			// and the skill walk must never read through it into this host.
			resolved := filepath.Clean(filepath.Join(filepath.Dir(target), header.Linkname))
			if filepath.IsAbs(header.Linkname) || !isWithin(resolved, destination) {
				return failure.Validation("omarchy-setup: commit %s links %s outside the checkout",
					commit[:12], header.Name)
			}
			if err = os.MkdirAll(filepath.Dir(target), 0o755); err == nil {
				err = os.Symlink(header.Linkname, target)
			}
		case tar.TypeXGlobalHeader:
			// git archive records the commit here; it is not a file.
		default:
			return failure.Validation("omarchy-setup: commit %s contains an unsupported entry %s",
				commit[:12], header.Name)
		}
		if err != nil {
			return err
		}
	}
}

// isWithin reports whether path is directory or below it.
func isWithin(path, directory string) bool {
	relative, err := filepath.Rel(directory, path)
	return err == nil && relative != ".." && !strings.HasPrefix(relative, ".."+string(filepath.Separator)) &&
		!filepath.IsAbs(relative)
}

// insideCheckout refuses a source whose real path, after every link is
// resolved, is not in the extracted checkout. A missing source is allowed; the
// caller decides what its absence means.
func insideCheckout(checkout, path string) error {
	root, err := filepath.EvalSymlinks(checkout)
	if err != nil {
		return err
	}
	resolved, err := filepath.EvalSymlinks(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil || !isWithin(resolved, root) {
		return failure.Validation("omarchy-setup: %s resolves outside the checkout", path)
	}
	return nil
}

// gitMode is the mode Git records for a file, which is all a checkout of it
// has: 0755 when it is executable and 0644 otherwise. The archive's own mode
// has the tar.umask setting applied and is not used as it stands, and the
// generator's output has the operator's umask applied, so both are normalised
// through this.
func gitMode(archived int64) os.FileMode {
	if archived&0o100 != 0 {
		return 0o755
	}
	return 0o644
}

func writeExtracted(target string, reader io.Reader, mode os.FileMode) error {
	file, err := os.OpenFile(target, os.O_WRONLY|os.O_CREATE|os.O_EXCL, mode)
	if err != nil {
		return err
	}
	if _, err := io.Copy(file, reader); err != nil {
		file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	// The umask must not decide what mode a skill file is published with.
	return os.Chmod(target, mode)
}

// derive runs the checkout's own generator against an empty scratch home and
// collects what it and the checkout install. The scratch home is the only
// home the generator sees, so nothing of this host's agent environment can
// leak into the release.
func derive(runner procx.Runner, scratch, checkout string, policy []byte) (agentenv.DerivedSources, error) {
	home := filepath.Join(scratch, "home")
	temporary := filepath.Join(scratch, "tmp")
	for _, directory := range []string{home, temporary} {
		if err := os.MkdirAll(directory, 0o700); err != nil {
			return agentenv.DerivedSources{}, err
		}
	}
	generator := filepath.Join(checkout, Generator)
	if info, err := os.Lstat(generator); err != nil || !info.Mode().IsRegular() || info.Mode().Perm()&0o100 == 0 {
		return agentenv.DerivedSources{}, failure.Validation(
			"omarchy-setup: the pinned commit has no executable %s", Generator)
	}
	if policy != nil {
		return derivePolicy(runner, scratch, checkout, home, temporary, policy)
	}
	generated := runner(procx.Command{
		Argv: []string{generator, "--root", checkout},
		Dir:  checkout,
		Env: []string{
			"HOME=" + home, "TMPDIR=" + temporary, "PATH=" + os.Getenv("PATH"), "LANG=C.UTF-8",
		},
		Timeout: 120 * time.Second,
	})
	if !generated.OK() {
		return agentenv.DerivedSources{}, failure.Validation("omarchy-setup: %s failed: %s",
			Generator, tail(strings.TrimSpace(generated.Output()), 400))
	}
	instructions := map[string]agentenv.DerivedFile{}
	add := func(relative, source string) error {
		info, err := os.Lstat(source)
		if errors.Is(err, os.ErrNotExist) {
			return nil
		}
		if err != nil {
			return err
		}
		if !info.Mode().IsRegular() {
			return failure.Validation("omarchy-setup: %s is not a regular file", relative)
		}
		content, err := os.ReadFile(source)
		if err != nil {
			return err
		}
		instructions[relative] = agentenv.DerivedFile{
			Content: content, Permissions: int64(gitMode(int64(info.Mode().Perm()))),
		}
		return nil
	}
	entries, err := os.ReadDir(filepath.Join(home, instructionDirectory))
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return agentenv.DerivedSources{}, err
	}
	for _, entry := range entries {
		// Capture publishes the Markdown files of this directory and nothing
		// else, so an authored release takes the same set.
		if !strings.HasSuffix(entry.Name(), ".md") {
			continue
		}
		relative := instructionDirectory + "/" + entry.Name()
		if err := add(relative, filepath.Join(home, relative)); err != nil {
			return agentenv.DerivedSources{}, err
		}
	}
	// The generator writes the managed block of ~/.codex/AGENTS.md; in an
	// empty home that block is the whole file, which is what a release carries.
	if err := add(".codex/AGENTS.md", filepath.Join(home, ".codex/AGENTS.md")); err != nil {
		return agentenv.DerivedSources{}, err
	}
	// The Claude global instructions are installed verbatim from the checkout.
	for _, source := range []string{
		filepath.Join(checkout, skillsDirectory), filepath.Join(checkout, "config/claude/CLAUDE.md"),
	} {
		if err := insideCheckout(checkout, source); err != nil {
			return agentenv.DerivedSources{}, err
		}
	}
	if err := add(".claude/omarchy-setup/CLAUDE.md", filepath.Join(checkout, "config/claude/CLAUDE.md")); err != nil {
		return agentenv.DerivedSources{}, err
	}
	return agentenv.DerivedSources{
		SkillsRoot:             filepath.Join(checkout, skillsDirectory),
		Instructions:           instructions,
		InstructionDirectories: []string{instructionDirectory},
	}, nil
}

// validate applies the checks authored publication applies to the bytes it
// publishes: the manifest validates, its companion files match, and its fleet
// intent names only inventory hosts.
func validate(root string, manifest map[string]any) (release.Release, error) {
	value, err := release.Validate(manifest)
	if err != nil {
		return release.Release{}, err
	}
	payload, err := value.CanonicalBytes()
	if err != nil {
		return release.Release{}, err
	}
	reread, err := canonjson.DecodeObject(payload)
	if err != nil {
		return release.Release{}, err
	}
	if value, err = release.Validate(reread); err != nil {
		return release.Release{}, err
	}
	if _, err := release.StoredFiles(root, value); err != nil {
		return release.Release{}, err
	}
	document, present, err := value.FleetIntent()
	if err != nil {
		return release.Release{}, err
	}
	if present {
		config, err := inventory.Load(root)
		if err != nil {
			return release.Release{}, err
		}
		if err := document.CheckInventory(config.KnownHosts()); err != nil {
			return release.Release{}, err
		}
	}
	return value, nil
}

func git(runner procx.Runner, directory string, timeout time.Duration, arguments ...string) (string, error) {
	result := runner(procx.Command{
		Argv:    append([]string{"git", "-C", directory}, arguments...),
		Timeout: timeout,
	})
	if !result.OK() {
		return "", failure.Validation("git %s failed in %s: %s",
			strings.Join(arguments, " "), directory, tail(strings.TrimSpace(result.Output()), 300))
	}
	return strings.TrimSpace(result.Stdout), nil
}

func digestOf(payload []byte) string {
	return agentenv.Digest(payload)
}

func tail(value string, size int) string {
	if len(value) <= size {
		return value
	}
	return value[len(value)-size:]
}

package agent

import (
	"github.com/iryzhkov/UpKeeper/internal/procx"
	"os"
	"strings"
	"testing"
)

const stewardLegacyUnitFixture = `# Generated by t3-steward install-service. Re-run with --force to regenerate.
[Unit]
Description=T3 quota watchdog (stops T3 agent sessions before the provider quota runs out)
Documentation=https://github.com/iryzhkov/t3-steward
After=t3code.service
PartOf=t3code.service

[Service]
Type=simple
ExecStart=/home/test/.local/bin/t3-steward run --config /home/test/.config/t3-steward/config.yaml
Restart=on-failure
RestartSec=5
# The default token command runs the t3 CLI, which needs node on PATH.
Environment=PATH=%h/.local/bin:/usr/bin:/bin
Environment=HOME=%h
# Modest hardening. ProtectHome and PrivateTmp are deliberately absent: the
# steward reads T3's logs, the t3 CLI writes T3's own database under $HOME,
# and wait checks written by agents must see the same /tmp the agents use.
NoNewPrivileges=true
ProtectSystem=full

[Install]
WantedBy=default.target
`

func TestStewardOwnedUnitMigration(t *testing.T) {
	for _, mode := range []string{"apply", "dry-run", "custom", "symlink", "restart-failure", "pending", "pending-drift", "compatible-custom", "oversize", "shadowed", "upgrade"} {
		t.Run(mode, func(t *testing.T) {
			host := stewardTestHost{active: true}
			if mode == "restart-failure" {
				host.restartFailures = 1
			}
			c, runner := stewardTestPrepare(t, host)
			originalHandle := runner.handle
			runner.handle = func(command procx.Command) procx.Result {
				if adapterTestMatches(command.Argv, "--property=ProtectSystem") {
					if mode == "shadowed" {
						return procx.Result{Stdout: "full\n"}
					}
					return procx.Result{Stdout: "no\n"}
				}
				return originalHandle(command)
			}
			spec := stewardTestSpec(false)
			c.Components["t3-steward"] = spec
			adapterTestWrite(t, c.Path(".local/bin/t3-steward"), stewardTestBinary)
			p := c.Path(".config/systemd/user/t3-steward.service")
			original := stewardLegacyUnitFixture
			if mode == "custom" {
				original = strings.Replace(original, "RestartSec=5", "RestartSec=17", 1)
			}
			adapterTestWrite(t, p, original)
			if mode == "compatible-custom" {
				original = strings.Replace(original, "ProtectSystem=full", "ProtectSystem=false", 1) + "# retained operator note\n"
				adapterTestWrite(t, p, original)
			}
			if mode == "pending" || mode == "pending-drift" {
				receipt := c.Path(stewardUnitPending)
				adapterTestWrite(t, receipt, stewardLegacyUnitFixture)
				if err := os.Chmod(receipt, 0600); err != nil {
					t.Fatal(err)
				}
				original = strings.Replace(original, "ProtectSystem=full", "ProtectSystem=false", 1)
				if mode == "pending-drift" {
					original += "# operator changed while interrupted\n"
				}
				adapterTestWrite(t, p, original)
			}
			if mode == "oversize" {
				f, err := os.OpenFile(p, os.O_WRONLY, 0)
				if err != nil {
					t.Fatal(err)
				}
				if err = f.Truncate(stewardUnitLimit + 1); err != nil {
					t.Fatal(err)
				}
				f.Close()
			}
			if mode == "symlink" {
				if err := os.Rename(p, p+".target"); err != nil {
					t.Fatal(err)
				}
				if err := os.Symlink(p+".target", p); err != nil {
					t.Fatal(err)
				}
			}
			c.DryRun = mode == "dry-run"
			actions := []string{}
			observed := map[string]any{"version": stewardTestVersion, "service_active": true}
			if mode == "upgrade" {
				observed["version"] = "0.0.1"
				archive := stewardTestArchive(t, []byte(stewardTestBinary), []byte(stewardTestHook), false)
				stewardTestServe(t, archive, stewardTestDigest(archive))
			}
			state, err := stewardApply(c, spec, observed, &actions)
			body, _ := os.ReadFile(p)
			switch mode {
			case "apply", "pending", "upgrade":
				if err != nil || state != "updated" || string(body) != strings.Replace(original, "ProtectSystem=full", "ProtectSystem=false", 1) || !runner.ran("daemon-reload") || !runner.ran("restart") {
					t.Fatalf("migration: state=%s err=%v calls=%v body=%s", state, err, runner.calls, body)
				}
				actions = nil
				state, err = stewardApply(c, spec, map[string]any{"version": stewardTestVersion, "service_active": true}, &actions)
				if err != nil || state != "converged" {
					t.Fatalf("repeat: %s %v", state, err)
				}
			case "compatible-custom":
				if err != nil || state != "converged" || string(body) != original || runner.ran("restart") {
					t.Fatalf("compatible customized unit changed: %s %v", state, err)
				}
			case "oversize":
				info, _ := os.Stat(p)
				if err == nil || info.Size() != stewardUnitLimit+1 {
					t.Fatal("oversize unit not preserved")
				}
			case "dry-run":
				if err != nil || state != "updated" || string(body) != original || runner.ran("restart") || runner.ran("daemon-reload") {
					t.Fatalf("dryrun: %s %v %v", state, err, runner.calls)
				}
			default:
				if err == nil || string(body) != original {
					t.Fatalf("unsafe migration: %s %v body=%s", state, err, body)
				}
			}
		})
	}
}

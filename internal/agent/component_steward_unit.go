const stewardUnitPath = ".config/systemd/user/t3-steward.service"
const stewardUnitPending = ".local/state/dev-fleet/unit-migrations/steward-protectsystem.pending"
const stewardUnitLimit = 64 * 1024
const stewardKnownUnit = `# Generated by t3-steward install-service. Re-run with --force to regenerate.
[Unit]
Description=T3 quota watchdog (stops T3 agent sessions before the provider quota runs out)
Documentation=https://github.com/iryzhkov/t3-steward
After=t3code.service
PartOf=t3code.service

[Service]
Type=simple
ExecStart=/home/test/.local/bin/t3-steward run --config /home/test/.config/t3-steward/config.yaml
Restart=on-failure
RestartSec=5
# The default token command runs the t3 CLI, which needs node on PATH.
Environment=PATH=%h/.local/bin:/usr/bin:/bin
Environment=HOME=%h
# Modest hardening. ProtectHome and PrivateTmp are deliberately absent: the
# steward reads T3's logs, the t3 CLI writes T3's own database under $HOME,
# and wait checks written by agents must see the same /tmp the agents use.
NoNewPrivileges=true
ProtectSystem=full

[Install]
WantedBy=default.target
`

func stewardKnownLegacyUnit(raw []byte) bool {
	pattern := regexp.QuoteMeta(stewardKnownUnit)
	pattern = strings.Replace(pattern, regexp.QuoteMeta("After=t3code.service\nPartOf=t3code.service\n"), "(?:After=([^\\r\\n]+)\nPartOf=([^\\r\\n]+)\n)?", 1)
	pattern = strings.Replace(pattern, regexp.QuoteMeta("ExecStart=/home/test/.local/bin/t3-steward run --config /home/test/.config/t3-steward/config.yaml"), "ExecStart=[^\\r\\n]+ run --config [^\\r\\n]+", 1)
	pattern = strings.Replace(pattern, regexp.QuoteMeta("Environment=PATH=%h/.local/bin:/usr/bin:/bin"), "Environment=PATH=[^\\r\\n]+", 1)
	match := regexp.MustCompile("\\A" + pattern + "\\z").FindSubmatch(raw)
	return match != nil && bytes.Equal(match[1], match[2])
}

func stewardReadUnit(c *Context) ([]byte, error) {
	p := c.Path(stewardUnitPath)
	if err := fleetOwnedPathSafe(c.Home, p); err != nil {
		return nil, err
	}
	f, err := os.OpenFile(p, os.O_RDONLY|syscall.O_NOFOLLOW|syscall.O_NONBLOCK, 0)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil {
		return nil, err
	}
	stat, ok := info.Sys().(*syscall.Stat_t)
	if !info.Mode().IsRegular() || info.Size() > stewardUnitLimit || info.Mode().Perm() != 0644 || !ok || stat.Uid != uint32(os.Getuid()) {
		return nil, Failf("Steward unit must be owner-owned regular mode 0644 within size limit")
	}
	raw, err := io.ReadAll(io.LimitReader(f, stewardUnitLimit+1))
	if len(raw) > stewardUnitLimit {
		return nil, Failf("Steward unit exceeds size limit")
	}
	return raw, err
}

// stewardUnitActivity admits only proven steady active/inactive states.
// is-active normally exits 3 for inactivity; runners may report it with 0.
func stewardUnitActivity(c *Context) (bool, error) {
	result := c.Run([]string{"systemctl", "--user", "is-active", "t3-steward.service"}, 0, "")
	if result.OK && result.Output == "active" {
		return true, nil
	}
	if (result.Code == 0 || result.Code == 3) && result.Output == "inactive" && !result.TimedOut {
		return false, nil
	}
	return false, Failf("cannot prove Steward unit activity: %s", result.Output)
}

// The pending original is durable before replacement. An interrupted activation
// is retried only when the live unit still equals either known transaction image.
func stewardApplyPinned(c *Context, spec, before map[string]any, actions *[]string) (string, error) {
	raw, err := stewardReadUnit(c)
	if err != nil {
		return "", err
	}
	pending, err := fleetReadPrivateBounded(c, stewardUnitPending, stewardUnitLimit)
	if err != nil {
		return "", err
	}
	original := raw
	if pending != nil {
		original = pending
	}
	needs := pending != nil || bytes.Contains(raw, []byte("ProtectSystem=full"))
	if !needs {
		return stewardApplyPinnedBinary(c, spec, before, actions)
	}
	if adapterSpecString(spec, "service") != "t3-steward.service" || !stewardKnownLegacyUnit(original) {
		return "", Failf("Steward unit is not the known generated legacy format; preserving customization")
	}
	replacement := bytes.Replace(original, []byte("ProtectSystem=full\n"), []byte("ProtectSystem=false\n"), 1)
	if !bytes.Equal(raw, original) && !bytes.Equal(raw, replacement) {
		return "", Failf("Steward unit changed during retained migration; preserving it")
	}
	if c.DryRun {
		*actions = append(*actions, "would migrate known generated Steward unit ProtectSystem=full to false")
		if _, err := stewardApplyPinnedBinary(c, spec, before, actions); err != nil {
			return "", err
		}
		return "updated", nil
	}
	// Observe activity independently of the binary observation, before any
	// migration effect. A failed/ambiguous probe is not proof of inactivity.
	priorActive, err := stewardUnitActivity(c)
	if err != nil {
		return "", err
	}
	receipt := c.Path(stewardUnitPending)
	if err := fleetOwnedPathSafe(c.Home, receipt); err != nil {
		return "", err
	}
	if pending == nil {
		if err := os.MkdirAll(filepath.Dir(receipt), 0700); err != nil {
			return "", err
		}
		if err := fsatomic.CreateExclusive(receipt, original, 0600); err != nil {
			return "", err
		}
		if err := fsatomic.SyncDirectory(filepath.Dir(receipt)); err != nil {
			return "", err
		}
	}
	// Keep a permanent private original, while pending remains the crash marker.
	archive, err := os.CreateTemp(filepath.Dir(receipt), "steward-unit-prior-*")
	if err != nil {
		return "", err
	}
	archivePath := archive.Name()
	archive.Close()
	if err := fsatomic.WritePrivateFile(archivePath, original); err != nil {
		return "", err
	}
	p := c.Path(stewardUnitPath)
	current, err := stewardReadUnit(c)
	if err != nil {
		return "", err
	}
	if !bytes.Equal(current, raw) {
		return "", Failf("Steward unit changed before activation")
	}
	if err := fsatomic.WriteFile(p, replacement, 0644); err != nil {
		return "", err
	}
	activateErr := func() error {
		if _, err := c.Must([]string{"systemctl", "--user", "daemon-reload"}, 0, "", "reload migrated Steward unit"); err != nil {
			return err
		}
		// Prove unit activation before replacing the binary. A shadowing drop-in
		// must not turn a successful binary install into a partial migration.
		if _, err := c.Must([]string{"systemctl", "--user", "restart", "t3-steward.service"}, 0, "", "activate migrated Steward unit"); err != nil {
			return err
		}
		if !c.UnitActive("t3-steward.service") {
			return Failf("migrated Steward unit is inactive")
		}
		effective, err := c.Must([]string{"systemctl", "--user", "show", "t3-steward.service", "--property=ProtectSystem", "--value"}, 0, "", "verify effective Steward unit")
		if err != nil {
			return err
		}
		if value := strings.TrimSpace(effective); value != "no" && value != "false" {
			return Failf("effective Steward ProtectSystem is not disabled; preserving unknown overrides")
		}
		_, err = stewardApplyPinnedBinary(c, spec, before, actions)
		return err
	}()
	if activateErr != nil {
		current, readErr := stewardReadUnit(c)
		if readErr != nil || !bytes.Equal(current, replacement) {
			return "", errors.Join(activateErr, Failf("rollback failed: unit rollback refused changed destination"))
		}
		restoreErr := fsatomic.WriteFile(p, original, 0644)
		if restoreErr == nil {
			_, restoreErr = c.Must([]string{"systemctl", "--user", "daemon-reload"}, 0, "", "reload restored Steward unit")
		}
		if restoreErr == nil {
			verb := "stop"
			if priorActive {
				verb = "restart"
			}
			_, restoreErr = c.Must([]string{"systemctl", "--user", verb, "t3-steward.service"}, 0, "", "restore prior Steward activity")
		}
		if restoreErr == nil {
			current, restoreErr = stewardReadUnit(c)
			if restoreErr == nil && !bytes.Equal(current, original) {
				restoreErr = Failf("restored Steward unit bytes differ from original")
			}
		}
		if restoreErr == nil {
			var restoredActive bool
			restoredActive, restoreErr = stewardUnitActivity(c)
			if restoreErr == nil && restoredActive != priorActive {
				restoreErr = Failf("restored Steward activity differs from prior state")
			}
		}
		// Command success alone does not prove restoration. An incomplete or
		// unverified rollback stops Execute before later components run.
		if restoreErr != nil {
			restoreErr = fmt.Errorf("rollback failed: restoring the original Steward unit: %w", restoreErr)
		}
		return "", errors.Join(activateErr, restoreErr)
	}
	if err := os.Remove(receipt); err != nil {
		return "", err
	}
	if err := fsatomic.SyncDirectory(filepath.Dir(receipt)); err != nil {
		return "", err
	}
	*actions = append(*actions, fmt.Sprintf("migrated generated Steward unit; retained original at %s", archivePath))
	return "updated", nil
}
